CREATE TABLE SOLICITUDES_PRESTAMO (
    ID_Solicitud_Prestamo  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario          VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    ID_Libro               VARCHAR(7)  NOT NULL REFERENCES LIBROS (ID_Libro),
    Fecha_Solicitud        TIMESTAMP   NOT NULL DEFAULT now(),
    Estatus                VARCHAR(12) NOT NULL DEFAULT 'Pendiente',
    CONSTRAINT ck_solicitudes_estatus CHECK (Estatus IN ('Pendiente', 'Atendida', 'Cancelada'))
);

CREATE TABLE LISTA_ESPERA (
    ID_Espera       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario   VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    ID_Libro        VARCHAR(7)  NOT NULL REFERENCES LIBROS (ID_Libro),
    Fecha_Registro  TIMESTAMP   NOT NULL DEFAULT now(),
    Estatus         VARCHAR(12) NOT NULL DEFAULT 'En espera',
    CONSTRAINT ck_espera_estatus CHECK (Estatus IN ('En espera', 'Notificado', 'Atendido', 'Cancelado'))
);
-- Evita inscripciones activas duplicadas del mismo usuario para el mismo libro
CREATE UNIQUE INDEX uq_espera_activa ON LISTA_ESPERA (Clave_Usuario, ID_Libro)
    WHERE Estatus IN ('En espera', 'Notificado');

-- =====================================================================
--  4. PRÉSTAMO DE LIBROS
-- =====================================================================

CREATE TABLE PRESTAMOS (
    ID_Prestamo            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario          VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    ID_Ejemplar            VARCHAR(10) NOT NULL REFERENCES EJEMPLARES (ID_Ejemplar),
    Clave_Bibliotecario    VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    ID_Solicitud_Prestamo  INTEGER     UNIQUE REFERENCES SOLICITUDES_PRESTAMO (ID_Solicitud_Prestamo),
    Fecha_Prestamo         DATE        NOT NULL DEFAULT CURRENT_DATE,
    Fecha_Vencimiento      DATE        NOT NULL,
    Estatus                VARCHAR(10) NOT NULL DEFAULT 'Activo',
    CONSTRAINT ck_prestamos_estatus CHECK (Estatus IN ('Activo', 'Devuelto', 'Perdido')),
    CONSTRAINT ck_prestamos_fechas  CHECK (Fecha_Vencimiento > Fecha_Prestamo)
);
-- A lo más un préstamo abierto por ejemplar
CREATE UNIQUE INDEX uq_prestamo_abierto ON PRESTAMOS (ID_Ejemplar) WHERE Estatus = 'Activo';

CREATE TABLE RENOVACIONES (
    ID_Renovacion         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Prestamo           INTEGER    NOT NULL REFERENCES PRESTAMOS (ID_Prestamo),
    Fecha_Renovacion      DATE       NOT NULL DEFAULT CURRENT_DATE,
    Vencimiento_Anterior  DATE       NOT NULL,
    Vencimiento_Nuevo     DATE       NOT NULL,
    Clave_Autoriza        VARCHAR(6) NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    CONSTRAINT ck_renovaciones_fechas CHECK (Vencimiento_Nuevo > Vencimiento_Anterior)
);

-- =====================================================================
--  5. DEVOLUCIÓN DE LIBROS
-- =====================================================================

CREATE TABLE DEVOLUCIONES (
    ID_Devolucion        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Prestamo          INTEGER     NOT NULL UNIQUE REFERENCES PRESTAMOS (ID_Prestamo),
    Fecha_Devolucion     DATE        NOT NULL DEFAULT CURRENT_DATE,
    Condicion_Recibida   VARCHAR(10) NOT NULL,
    Clave_Bibliotecario  VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    CONSTRAINT ck_devoluciones_condicion CHECK (Condicion_Recibida IN ('Bueno', 'Regular', 'Dañado'))
);

CREATE TABLE MULTAS (
    ID_Multa               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Prestamo            INTEGER       NOT NULL REFERENCES PRESTAMOS (ID_Prestamo),
    Tipo                   VARCHAR(12)   NOT NULL,
    Dias_Retraso           INTEGER       CHECK (Dias_Retraso > 0),
    Tarifa_Diaria_Aplicada DECIMAL(8,2)  CHECK (Tarifa_Diaria_Aplicada >= 0),
    Precio_USD_Aplicado    DECIMAL(10,2) CHECK (Precio_USD_Aplicado >= 0),
    Tipo_Cambio            DECIMAL(8,4)  CHECK (Tipo_Cambio > 0),
    -- Retraso: días × tarifa. Pérdida: precio USD × tipo de cambio
    Monto                  DECIMAL(10,2) GENERATED ALWAYS AS (
                               CASE WHEN Tipo = 'Retraso'
                                    THEN Dias_Retraso * Tarifa_Diaria_Aplicada
                                    ELSE round(Precio_USD_Aplicado * Tipo_Cambio, 2)
                               END) STORED,
    Fecha_Generacion       DATE          NOT NULL DEFAULT CURRENT_DATE,
    Estatus                VARCHAR(10)   NOT NULL DEFAULT 'Pendiente',
    CONSTRAINT ck_multas_tipo    CHECK (Tipo IN ('Retraso', 'Reposición')),
    CONSTRAINT ck_multas_estatus CHECK (Estatus IN ('Pendiente', 'Pagada')),
    CONSTRAINT ck_multas_retraso CHECK (Tipo <> 'Retraso'
                                        OR (Dias_Retraso IS NOT NULL AND Tarifa_Diaria_Aplicada IS NOT NULL)),
    CONSTRAINT ck_multas_reposicion CHECK (Tipo <> 'Reposición'
                                        OR (Precio_USD_Aplicado IS NOT NULL AND Tipo_Cambio IS NOT NULL))
);

CREATE TABLE PAGOS_MULTA (
    ID_Pago              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Multa             INTEGER     NOT NULL UNIQUE REFERENCES MULTAS (ID_Multa),
    Folio_Tesoreria      VARCHAR(30) NOT NULL,
    Fecha_Pago           DATE        NOT NULL DEFAULT CURRENT_DATE,
    Clave_Bibliotecario  VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario)
);

CREATE TABLE NOTIFICACIONES_TESORERIA (
    ID_Notificacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Multa         INTEGER     NOT NULL UNIQUE REFERENCES MULTAS (ID_Multa),
    Clave_Emisor     VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    Fecha_Creacion   TIMESTAMP   NOT NULL DEFAULT now(),
    Fecha_Envio      TIMESTAMP,
    Fecha_Acuse      TIMESTAMP,
    Estatus          VARCHAR(10) NOT NULL DEFAULT 'Pendiente',
    CONSTRAINT ck_notif_estatus CHECK (Estatus IN ('Pendiente', 'Enviada', 'Recibida', 'Error')),
    CONSTRAINT ck_notif_envio   CHECK (Estatus NOT IN ('Enviada', 'Recibida') OR Fecha_Envio IS NOT NULL),
    CONSTRAINT ck_notif_acuse   CHECK (Estatus <> 'Recibida' OR Fecha_Acuse IS NOT NULL)
);

CREATE TABLE AVISOS (
    ID_Aviso       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario  VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    ID_Multa       INTEGER     REFERENCES MULTAS (ID_Multa),
    Area_Destino   VARCHAR(25) NOT NULL,
    Tipo           VARCHAR(25) NOT NULL,
    Fecha_Aviso    DATE        NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_avisos_area CHECK (Area_Destino IN ('Servicios Escolares', 'Tesorería')),
    CONSTRAINT ck_avisos_tipo CHECK (Tipo IN ('Libro perdido', 'Suspensión por adeudo')),
    -- El aviso de libro perdido siempre se origina en una multa de reposición
    CONSTRAINT ck_avisos_perdido CHECK (Tipo <> 'Libro perdido' OR ID_Multa IS NOT NULL)
);

-- =====================================================================
--  BITÁCORA, AVISOS Y CHATBOT
-- =====================================================================

CREATE TABLE BITACORA (
    ID_Bitacora    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario  VARCHAR(6)   REFERENCES USUARIOS (Clave_Usuario),   -- nulo = proceso automático
    Fecha_Hora     TIMESTAMP    NOT NULL DEFAULT now(),
    Accion         VARCHAR(50)  NOT NULL,
    Detalle        VARCHAR(255)
);

CREATE TABLE CONTENIDOS_CHATBOT (
    ID_Contenido         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Tipo_Fuente          VARCHAR(20)  NOT NULL,
    Referencia           VARCHAR(100) NOT NULL,
    Titulo               VARCHAR(150) NOT NULL,
    Contenido            TEXT         NOT NULL,
    Version              VARCHAR(20)  NOT NULL,
    Estatus              VARCHAR(10)  NOT NULL DEFAULT 'Activo',
    Fecha_Actualizacion  TIMESTAMP    NOT NULL DEFAULT now(),
    Clave_Responsable    VARCHAR(6)   NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    CONSTRAINT ck_contenidos_fuente  CHECK (Tipo_Fuente IN ('Historia de usuario', 'Regla de negocio', 'Manual')),
    CONSTRAINT ck_contenidos_estatus CHECK (Estatus IN ('Activo', 'Inactivo'))
);

CREATE TABLE PREGUNTAS_CHATBOT (
    ID_Pregunta          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Pregunta             VARCHAR(300) NOT NULL UNIQUE,
    Respuesta            TEXT         NOT NULL,
    Estatus              VARCHAR(10)  NOT NULL DEFAULT 'Activa',
    Fecha_Actualizacion  TIMESTAMP    NOT NULL DEFAULT now(),
    Clave_Responsable    VARCHAR(6)   NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    CONSTRAINT ck_preguntas_estatus CHECK (Estatus IN ('Activa', 'Inactiva'))
);

-- N:M entre PREGUNTAS_CHATBOT y CONTENIDOS_CHATBOT
CREATE TABLE PREGUNTA_CONTENIDO (
    ID_Pregunta   INTEGER NOT NULL REFERENCES PREGUNTAS_CHATBOT (ID_Pregunta)   ON DELETE CASCADE,
    ID_Contenido  INTEGER NOT NULL REFERENCES CONTENIDOS_CHATBOT (ID_Contenido) ON DELETE RESTRICT,
    PRIMARY KEY (ID_Pregunta, ID_Contenido)
);

