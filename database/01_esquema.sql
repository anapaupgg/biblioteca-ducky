DROP SCHEMA IF EXISTS biblioteca CASCADE;
CREATE SCHEMA biblioteca;
SET search_path TO biblioteca, public;

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- hash de contraseñas (crypt / gen_salt)

DO $$ BEGIN
    EXECUTE format('ALTER DATABASE %I SET search_path = biblioteca, public', current_database());
END $$;

-- =====================================================================
--  1. GESTIÓN DE USUARIOS
-- =====================================================================

CREATE TABLE PERFILES (
    ID_Perfil          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre             VARCHAR(50)  NOT NULL UNIQUE,
    Descripcion        VARCHAR(200),
    Estatus            VARCHAR(10)  NOT NULL DEFAULT 'Activo',
    Fecha_Alta         DATE         NOT NULL DEFAULT CURRENT_DATE,
    Clave_Admin_Alta   VARCHAR(6)   NOT NULL,           -- FK a USUARIOS (se agrega al final)
    Fecha_Baja         DATE,
    Clave_Admin_Baja   VARCHAR(6),                      -- FK a USUARIOS (se agrega al final)
    CONSTRAINT ck_perfiles_estatus CHECK (Estatus IN ('Activo', 'Inactivo')),
    CONSTRAINT ck_perfiles_fechas  CHECK (Fecha_Baja IS NULL OR Fecha_Baja >= Fecha_Alta),
    CONSTRAINT ck_perfiles_baja    CHECK ((Fecha_Baja IS NULL) = (Clave_Admin_Baja IS NULL))
);

CREATE TABLE FUNCIONES (
    ID_Funcion   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre       VARCHAR(60) NOT NULL UNIQUE,
    Descripcion  VARCHAR(200)
);

-- N:M entre PERFILES y FUNCIONES
CREATE TABLE PERFIL_FUNCION (
    ID_Perfil   INTEGER NOT NULL REFERENCES PERFILES (ID_Perfil)   ON DELETE CASCADE,
    ID_Funcion  INTEGER NOT NULL REFERENCES FUNCIONES (ID_Funcion) ON DELETE RESTRICT,
    PRIMARY KEY (ID_Perfil, ID_Funcion)
);

CREATE TABLE TIPOS_USUARIO (
    ID_Tipo_Usuario  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre           VARCHAR(30)  NOT NULL UNIQUE,
    Dias_Prestamo    INTEGER      NOT NULL CHECK (Dias_Prestamo > 0),
    Max_Renovaciones INTEGER      NOT NULL CHECK (Max_Renovaciones >= 0),
    Max_Ejemplares   INTEGER      NOT NULL CHECK (Max_Ejemplares > 0),
    Multa_Diaria     DECIMAL(8,2) NOT NULL CHECK (Multa_Diaria >= 0)
);

CREATE TABLE USUARIOS (
    Clave_Usuario     VARCHAR(6)   PRIMARY KEY,
    Nombre            VARCHAR(100) NOT NULL,
    Correo            VARCHAR(100) NOT NULL UNIQUE,
    ID_Tipo_Usuario   INTEGER      NOT NULL REFERENCES TIPOS_USUARIO (ID_Tipo_Usuario),
    ID_Perfil         INTEGER      NOT NULL REFERENCES PERFILES (ID_Perfil),
    Estatus           VARCHAR(8)   NOT NULL DEFAULT 'Activo',
    Fecha_Alta        DATE         NOT NULL DEFAULT CURRENT_DATE,
    Clave_Admin_Alta  VARCHAR(6)   REFERENCES USUARIOS (Clave_Usuario),   -- recursiva, 0..1
    CONSTRAINT ck_usuarios_clave   CHECK (char_length(Clave_Usuario) = 6),
    CONSTRAINT ck_usuarios_correo  CHECK (Correo LIKE '%_@_%._%'),
    CONSTRAINT ck_usuarios_estatus CHECK (Estatus IN ('Activo', 'Inactivo'))
);

-- DEFERRABLE para poder crear el primer perfil y el primer administrador juntos
ALTER TABLE PERFILES
    ADD CONSTRAINT fk_perfiles_admin_alta FOREIGN KEY (Clave_Admin_Alta)
        REFERENCES USUARIOS (Clave_Usuario) DEFERRABLE INITIALLY DEFERRED,
    ADD CONSTRAINT fk_perfiles_admin_baja FOREIGN KEY (Clave_Admin_Baja)
        REFERENCES USUARIOS (Clave_Usuario) DEFERRABLE INITIALLY DEFERRED;

-- 1:1 con USUARIOS
CREATE TABLE CREDENCIALES (
    Clave_Usuario      VARCHAR(6)   PRIMARY KEY REFERENCES USUARIOS (Clave_Usuario) ON DELETE CASCADE,
    Contrasena_Hash    VARCHAR(255) NOT NULL,
    Es_Temporal        BOOLEAN      NOT NULL DEFAULT TRUE,
    Intentos_Fallidos  INTEGER      NOT NULL DEFAULT 0 CHECK (Intentos_Fallidos >= 0),
    Bloqueado_Hasta    TIMESTAMP,
    Ultimo_Acceso      TIMESTAMP
);

CREATE TABLE RECUPERACIONES_ACCESO (
    ID_Recuperacion   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario     VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    Token_Hash        VARCHAR(64) NOT NULL UNIQUE,
    Fecha_Solicitud   TIMESTAMP   NOT NULL DEFAULT now(),
    Fecha_Expiracion  TIMESTAMP   NOT NULL,
    Usado             BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_recuperacion_30min CHECK (Fecha_Expiracion = Fecha_Solicitud + INTERVAL '30 minutes')
);

CREATE TABLE SESIONES (
    ID_Sesion      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario  VARCHAR(6)   NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    Dispositivo    VARCHAR(100),
    Fecha_Inicio   TIMESTAMP    NOT NULL DEFAULT now(),
    Fecha_Fin      TIMESTAMP,
    CONSTRAINT ck_sesiones_fechas CHECK (Fecha_Fin IS NULL OR Fecha_Fin >= Fecha_Inicio)
);

CREATE TABLE MOTIVOS_BAJA (
    ID_Motivo    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Descripcion  VARCHAR(60) NOT NULL,
    Aplica_A     VARCHAR(10) NOT NULL,
    CONSTRAINT ck_motivos_aplica CHECK (Aplica_A IN ('Usuario', 'Ejemplar')),
    CONSTRAINT uq_motivos UNIQUE (Descripcion, Aplica_A)
);

CREATE TABLE BAJAS_USUARIO (
    ID_Baja_Usuario            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Clave_Usuario              VARCHAR(6)   NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    ID_Motivo                  INTEGER      NOT NULL REFERENCES MOTIVOS_BAJA (ID_Motivo),
    Comentario                 VARCHAR(200),
    Fecha_Baja                 DATE         NOT NULL DEFAULT CURRENT_DATE,
    Fecha_Reactivacion         DATE,
    Clave_Admin_Reactivacion   VARCHAR(6)   REFERENCES USUARIOS (Clave_Usuario),
    Clave_Administrador        VARCHAR(6)   NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    CONSTRAINT ck_bajas_usuario_fechas CHECK (Fecha_Reactivacion IS NULL OR Fecha_Reactivacion >= Fecha_Baja),
    CONSTRAINT ck_bajas_usuario_reactiva CHECK ((Fecha_Reactivacion IS NULL) = (Clave_Admin_Reactivacion IS NULL)),
    CONSTRAINT ck_bajas_usuario_comentario CHECK (Comentario IS NULL OR btrim(Comentario) <> '')
);

-- =====================================================================
--  2. GESTIÓN DE LIBROS
-- =====================================================================

CREATE TABLE EDITORIALES (
    ID_Editorial     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre           VARCHAR(100) NOT NULL UNIQUE,
    Correo_Contacto  VARCHAR(100)
);

CREATE TABLE TEMAS (
    ID_Tema  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre   VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE AUTORES (
    ID_Autor  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre    VARCHAR(100) NOT NULL
);

CREATE TABLE LIBROS (
    ID_Libro                  VARCHAR(7)    PRIMARY KEY,
    Titulo                    VARCHAR(150)  NOT NULL,
    ISBN                      VARCHAR(13)   NOT NULL UNIQUE,
    ID_Editorial              INTEGER       NOT NULL REFERENCES EDITORIALES (ID_Editorial),
    ID_Tema                   INTEGER       NOT NULL REFERENCES TEMAS (ID_Tema),
    Edicion                   VARCHAR(30),
    Anio_Publicacion          INTEGER       CHECK (Anio_Publicacion BETWEEN 1450 AND 2100),
    Paginas                   INTEGER       CHECK (Paginas > 0),
    Sinopsis                  VARCHAR(500),
    Formato                   VARCHAR(10)   NOT NULL,
    Enlace_Digital            VARCHAR(255),
    Precio_Ultima_Compra_USD  DECIMAL(10,2) CHECK (Precio_Ultima_Compra_USD >= 0),
    Estatus                   VARCHAR(25)   NOT NULL DEFAULT 'Ficha creada',
    Fecha_Alta_Catalogo       DATE,
    CONSTRAINT ck_libros_clave   CHECK (ID_Libro ~ '^L[0-9]{6}$'),
    CONSTRAINT ck_libros_isbn    CHECK (ISBN ~ '^([0-9]{9}[0-9X]|[0-9]{13})$'),
    CONSTRAINT ck_libros_formato CHECK (Formato IN ('Físico', 'Digital')),
    CONSTRAINT ck_libros_enlace  CHECK (Formato <> 'Digital' OR Enlace_Digital IS NOT NULL),
    CONSTRAINT ck_libros_estatus CHECK (Estatus IN ('Ficha creada', 'Activo en catálogo', 'Retirado')),
    CONSTRAINT ck_libros_alta    CHECK (Estatus = 'Ficha creada' OR Fecha_Alta_Catalogo IS NOT NULL)
);

-- N:M entre LIBROS y AUTORES
CREATE TABLE LIBRO_AUTOR (
    ID_Libro      VARCHAR(7) NOT NULL REFERENCES LIBROS (ID_Libro) ON DELETE CASCADE,
    ID_Autor      INTEGER    NOT NULL REFERENCES AUTORES (ID_Autor),
    Es_Principal  BOOLEAN    NOT NULL DEFAULT FALSE,
    PRIMARY KEY (ID_Libro, ID_Autor)
);
-- Un solo autor principal por libro
CREATE UNIQUE INDEX uq_libro_autor_principal ON LIBRO_AUTOR (ID_Libro) WHERE Es_Principal;

CREATE TABLE UBICACIONES (
    ID_Ubicacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Estante       VARCHAR(5)  NOT NULL,
    Fila          VARCHAR(5)  NOT NULL,
    Seccion       VARCHAR(50),
    CONSTRAINT uq_ubicacion UNIQUE NULLS NOT DISTINCT (Seccion, Estante, Fila)
);

CREATE TABLE EJEMPLARES (
    ID_Ejemplar    VARCHAR(10) PRIMARY KEY,
    ID_Libro       VARCHAR(7)  NOT NULL REFERENCES LIBROS (ID_Libro),
    ID_Ubicacion   INTEGER     REFERENCES UBICACIONES (ID_Ubicacion),
    Tipo_Uso       VARCHAR(20) NOT NULL DEFAULT 'Préstamo externo',
    Condicion      VARCHAR(10) NOT NULL DEFAULT 'Bueno',
    Estatus        VARCHAR(12) NOT NULL DEFAULT 'Disponible',
    Fecha_Ingreso  DATE        NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_ejemplares_uso       CHECK (Tipo_Uso IN ('Préstamo externo', 'Préstamo en sala', 'Reservado', 'Préstamo digital')),
    CONSTRAINT ck_ejemplares_condicion CHECK (Condicion IN ('Bueno', 'Regular', 'Dañado')),
    CONSTRAINT ck_ejemplares_estatus   CHECK (Estatus IN ('Disponible', 'Prestado', 'Perdido', 'Baja'))
);

CREATE TABLE BAJAS_EJEMPLAR (
    ID_Baja_Ejemplar     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Ejemplar          VARCHAR(10)  NOT NULL UNIQUE REFERENCES EJEMPLARES (ID_Ejemplar),
    ID_Motivo            INTEGER      NOT NULL REFERENCES MOTIVOS_BAJA (ID_Motivo),
    Descripcion          VARCHAR(200),
    Fecha_Baja           DATE         NOT NULL DEFAULT CURRENT_DATE,
    Clave_Administrador  VARCHAR(6)   NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    CONSTRAINT ck_bajas_ejemplar_desc CHECK (Descripcion IS NULL OR btrim(Descripcion) <> '')
);

CREATE TABLE PRESUPUESTOS_MENSUALES (
    ID_Presupuesto       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Periodo              CHAR(7)        NOT NULL UNIQUE,
    Moneda               CHAR(3)        NOT NULL DEFAULT 'MXN',
    Monto_Autorizado     DECIMAL(12,2)  NOT NULL,
    Fecha_Autorizacion   DATE           NOT NULL DEFAULT CURRENT_DATE,
    Clave_Responsable    VARCHAR(6)     NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    CONSTRAINT ck_presupuesto_periodo CHECK (Periodo ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    CONSTRAINT ck_presupuesto_moneda  CHECK (Moneda = 'MXN'),
    CONSTRAINT ck_presupuesto_monto   CHECK (Monto_Autorizado > 0)
);

CREATE TABLE PEDIDOS_TESORERIA (
    ID_Pedido          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Presupuesto     INTEGER     NOT NULL REFERENCES PRESUPUESTOS_MENSUALES (ID_Presupuesto),
    Clave_Solicitante  VARCHAR(6)  NOT NULL REFERENCES USUARIOS (Clave_Usuario),
    Fecha_Envio        TIMESTAMP   NOT NULL DEFAULT now(),
    Estatus            VARCHAR(15) NOT NULL DEFAULT 'Enviado',
    Fecha_Recepcion    DATE,
    CONSTRAINT ck_pedidos_estatus   CHECK (Estatus IN ('Enviado', 'Autorizado', 'Recibido', 'Rechazado')),
    CONSTRAINT ck_pedidos_recepcion CHECK ((Estatus = 'Recibido') = (Fecha_Recepcion IS NOT NULL))
);

CREATE TABLE DETALLE_PEDIDO (
    ID_Pedido                INTEGER       NOT NULL REFERENCES PEDIDOS_TESORERIA (ID_Pedido) ON DELETE CASCADE,
    Numero_Linea             INTEGER       NOT NULL CHECK (Numero_Linea > 0),
    ID_Libro                 VARCHAR(7)    REFERENCES LIBROS (ID_Libro),
    ISBN_Solicitado          VARCHAR(13)   CHECK (ISBN_Solicitado ~ '^([0-9]{9}[0-9X]|[0-9]{13})$'),
    Titulo_Solicitado        VARCHAR(150)  NOT NULL,
    ID_Editorial_Solicitada  INTEGER       REFERENCES EDITORIALES (ID_Editorial),
    Cantidad                 INTEGER       NOT NULL CHECK (Cantidad > 0),
    Costo_Unitario_MXN       DECIMAL(12,2) NOT NULL CHECK (Costo_Unitario_MXN >= 0),
    Clave_Peticionario       VARCHAR(6)    REFERENCES USUARIOS (Clave_Usuario),
    PRIMARY KEY (ID_Pedido, Numero_Linea)
);

CREATE TABLE DETALLE_PEDIDO_AUTOR (
    ID_Pedido     INTEGER NOT NULL,
    Numero_Linea  INTEGER NOT NULL,
    ID_Autor      INTEGER NOT NULL REFERENCES AUTORES (ID_Autor),
    PRIMARY KEY (ID_Pedido, Numero_Linea, ID_Autor),
    FOREIGN KEY (ID_Pedido, Numero_Linea)
        REFERENCES DETALLE_PEDIDO (ID_Pedido, Numero_Linea) ON DELETE CASCADE
);

